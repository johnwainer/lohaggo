/** Same file whatever transformation is in the URL: the Cloudinary public id, or the URL without it. */
export function assetKey(r: { publicId?: string | null; originalUrl?: string | null; url: string }) {
  if (r.publicId) return `pid:${r.publicId}`
  return `url:${(r.originalUrl || r.url).split('?')[0]}`
}

export function orientationOf(w: number | null | undefined, h: number | null | undefined): Orientation | null {
  if (!w || !h) return null
  const r = w / h
  return r < 0.9 ? 'portrait' : r > 1.1 ? 'landscape' : 'square'
}

/** Feed takes 4:5 to ~1:1 (an AI 2:3 is cropped to 4:5); reels and stories want tall files; Facebook and the blog, wide ones. */
export function formatFit(w: number | null | undefined, h: number | null | undefined): FormatFit[] {
  if (!w || !h) return []
  const r = w / h
  const out: FormatFit[] = []
  if (r >= 0.6 && r <= 1.1) out.push('feed')
  if (r <= 0.8) out.push('vertical')
  if (r >= 1.2) out.push('landscape')
  return out
}

export function previewOf(url: string, kind: 'image' | 'video') {
  if (kind === 'video') return videoPosterUrl(url) ?? url
  return isCloudinaryUrl(url) && url.includes('/image/upload/') ? url.replace('/upload/', '/upload/c_limit,w_600/') : url
}

/** Cloudinary serves the file as a download with fl_attachment; other URLs as they are. */
export function downloadUrl(url: string) {
  return isCloudinaryUrl(url) ? url.replace('/upload/', '/upload/fl_attachment/') : url
}

export function styleLabel(style: string | null | undefined) {
  if (!style) return null
  const s = IMAGE_STYLES.find((x) => x.id === style || x.prompt === style)
  return s?.label ?? (style.length <= 40 ? style : 'Estilo propio')
}

const norm = (s: string) => s.toLowerCase().normalize('NFD').replace(/[̀-ͯ]/g, '').trim()
const iso = (d: Date) => d.toISOString()
const score = (r: PostResultView | null) => (r ? r.reach + r.webViews : -1)

/** The service of a post: what the agent recorded, else the catalog service its title names. */
export function serviceOfPost(p: { title: string; service: string | null }, catalog: string[]) {
  return p.service || matchServices(p.title, '', catalog)[0] || null
}

/**
 * One entry per file: the posts that used it (a still video is the same photo animated, not another
 * resource), the AI candidates nobody chose, and the archive marks (latest wins).
 */
export function buildLibrary(p: { media: MediaRow[]; candidates: CandidateRow[]; posts: PostInfo[]; archived: Set<string> }): LibraryAsset[] {
  const posts = new Map(p.posts.map((x) => [x.id, x]))
  const out = new Map<string, LibraryAsset & { _posts: Set<string> }>()
  const add = <T>(list: T[], v: T | null | undefined) => { if (v && !list.includes(v)) list.push(v) }
  const tagFrom = (a: LibraryAsset, post: PostInfo | undefined) => {
    if (!post) return
    add(a.services, post.service)
    add(a.pillars, post.pillar)
    add(a.styles, styleLabel(post.style))
  }
  const blank = (key: string, kind: 'image' | 'video', url: string, d: Partial<LibraryAsset>, createdAt: Date): LibraryAsset & { _posts: Set<string> } => ({
    key, kind, origin: 'upload', url, previewUrl: previewOf(url, kind), publicId: null, alt: null, credit: null, creditUrl: null, width: null, height: null, durationSec: null,
    orientation: null, formats: [], services: [], pillars: [], styles: [], prompt: null, uses: 0, usedIn: [], firstUsedAt: null, lastUsedAt: null,
    createdAt: iso(createdAt), candidate: false, best: null, archived: p.archived.has(key), _posts: new Set<string>(), ...d,
  })

  for (const m of [...p.media].sort((a, b) => a.createdAt.getTime() - b.createdAt.getTime())) {
    if (m.kind === 'video' && isStillVideo(m.url)) continue
    const kind = m.kind === 'video' ? 'video' : 'image'
    const url = m.originalUrl || m.url
    const key = assetKey(m)
    const a = out.get(key) ?? blank(key, kind, url, {
      origin: mediaOrigin(m.source), publicId: m.publicId, width: m.width, height: m.height, durationSec: m.durationSec,
      orientation: orientationOf(m.width, m.height), formats: kind === 'video' ? (orientationOf(m.width, m.height) === 'portrait' ? ['vertical'] : []) : formatFit(m.width, m.height),
    }, m.createdAt)
    a.alt ||= m.alt
    a.credit ||= m.credit
    a.creditUrl ||= m.creditUrl
    const post = posts.get(m.postId)
    if (post && !a._posts.has(post.id)) {
      a._posts.add(post.id)
      const at = post.publishedAt ?? m.createdAt
      a.usedIn.push({ postId: post.id, title: post.title, status: post.status, at: iso(at), result: post.result })
      if (!a.firstUsedAt || iso(at) < a.firstUsedAt) a.firstUsedAt = iso(at)
      if (!a.lastUsedAt || iso(at) > a.lastUsedAt) a.lastUsedAt = iso(at)
      if (post.result && score(post.result) > score(a.best)) a.best = { ...post.result, postId: post.id, title: post.title }
      tagFrom(a, post)
    }
    out.set(key, a)
  }

  for (const c of p.candidates) {
    const key = assetKey(c)
    const a = out.get(key) ?? blank(key, 'image', c.url, {
      origin: 'ai', publicId: c.publicId, width: c.width, height: c.height, orientation: orientationOf(c.width, c.height) ?? ((c.orientation as Orientation | null) || null), formats: formatFit(c.width, c.height),
      credit: c.credit,
    }, c.createdAt)
    a.candidate = true
    a.prompt ||= c.prompt
    add(a.services, c.service)
    add(a.styles, styleLabel(c.style))
    if (!a.usedIn.length) tagFrom(a, c.postId ? posts.get(c.postId) : undefined)
    out.set(key, a)
  }

  return Array.from(out.values())
    .map(({ _posts, ...a }) => { void _posts; return { ...a, uses: a.usedIn.length, usedIn: a.usedIn.sort((x, y) => y.at.localeCompare(x.at)) } })
    .sort((a, b) => (b.lastUsedAt ?? b.createdAt).localeCompare(a.lastUsedAt ?? a.createdAt))
}

export type LibraryFilters = { kind?: string; service?: string; origin?: string; orientation?: string; usage?: '' | 'unused' | 'used'; q?: string; archived?: boolean }

export function filterLibrary(assets: LibraryAsset[], f: LibraryFilters) {
  const q = f.q ? norm(f.q) : ''
  return assets.filter((a) => {
    if (Boolean(f.archived) !== a.archived) return false
    if (f.kind && a.kind !== f.kind) return false
    if (f.origin && a.origin !== f.origin) return false
    if (f.orientation && a.orientation !== f.orientation) return false
    if (f.service && !a.services.some((s) => norm(s) === norm(f.service!))) return false
    if (f.usage === 'unused' && a.uses > 0) return false
    if (f.usage === 'used' && !a.uses) return false
    if (q) {
      const hay = norm([a.alt, a.prompt, a.credit, ...a.services, ...a.pillars, ...a.styles, ...a.usedIn.map((u) => u.title)].filter(Boolean).join(' '))
      if (!q.split(/\s+/).every((w) => hay.includes(w))) return false
    }
    return true
  })
}

/** Facets for the filters, from what the library holds. */
export function libraryFacets(assets: LibraryAsset[]) {
  const services = Array.from(new Set(assets.flatMap((a) => a.services))).sort((a, b) => a.localeCompare(b, 'es'))
  const origins = Array.from(new Set(assets.map((a) => a.origin))).sort()
  return { services, origins }
}

/**
 * Library images the agent may reuse for a piece: same service, the orientation it needs, not archived
 * and not used in the last `afterDays` days. Unchosen AI candidates first (paid, never shown), then the
 * ones whose posts did best, then the ones rested longest.
 */
export function pickReusable(assets: LibraryAsset[], want: { service: string | null; orientation: Orientation; n: number; afterDays: number; now: Date; excludeKeys?: Set<string>; excludePostId?: string }) {
  if (!want.service || want.n < 1) return []
  const svc = norm(want.service)
  const cutoff = new Date(want.now.getTime() - want.afterDays * 24 * 3600_000).toISOString()
  return assets
    .filter((a) => a.kind === 'image' && !a.archived && a.orientation === want.orientation)
    .filter((a) => a.services.some((s) => norm(s) === svc))
    .filter((a) => !want.excludeKeys?.has(a.key) && !a.usedIn.some((u) => u.postId === want.excludePostId))
    .filter((a) => !a.lastUsedAt || a.lastUsedAt < cutoff)
    .sort((a, b) => {
      const fresh = (x: LibraryAsset) => (x.candidate && !x.uses ? 0 : 1)
      if (fresh(a) !== fresh(b)) return fresh(a) - fresh(b)
      if (fresh(a) === 0) return b.createdAt.localeCompare(a.createdAt)
      const d = score(b.best) - score(a.best)
      if (d) return d
      return (a.lastUsedAt ?? '').localeCompare(b.lastUsedAt ?? '')
    })
    .slice(0, want.n)
}

export type PieceRow = {
  postId: string; title: string; publishedAt: string | null; channels: string[]; formats: Record<string, string>; thumb: string | null
  reach: number; webViews: number; engagementRate: number | null; requests: number; bookings: number; service: string | null; reeditions: number
}

/** Pieces that worked: what the platform lives on first (bookings, requests), then reach and engagement. */
export function rankPieces<T extends Pick<PieceRow, 'bookings' | 'requests' | 'reach' | 'webViews' | 'engagementRate'>>(rows: T[]) {
  return [...rows].sort((a, b) => b.bookings - a.bookings || b.requests - a.requests || (b.reach + b.webViews) - (a.reach + a.webViews) || (b.engagementRate ?? 0) - (a.engagementRate ?? 0))
}

export const REEDITION_SUFFIX = ' (reedición)'

/** «Título (reedición)», within the 200 characters a title has; a reedition of a reedition keeps one suffix. */
export function reeditionTitle(title: string) {
  const base = title.endsWith(REEDITION_SUFFIX) ? title.slice(0, -REEDITION_SUFFIX.length) : title
  return `${base.slice(0, 200 - REEDITION_SUFFIX.length)}${REEDITION_SUFFIX}`
}

/** Archive marks in the audit log, oldest first: the latest one of each resource wins. */
export function archivedKeys(marks: Array<{ details: string | null }>) {
  const set = new Set<string>()
  for (const m of marks) {
    try {
      const d = JSON.parse(m.details || '{}') as { key?: unknown; archived?: unknown }
      if (typeof d.key !== 'string') continue
      if (d.archived === false) set.delete(d.key)
      else set.add(d.key)
    } catch { /* malformed mark */ }
  }
  return set
}

/** A candidate's audit-log details → row (null when it is not one of ours). */
export function readCandidate(r: { id: string; entityId: string | null; createdAt: Date; details: string | null }): CandidateRow | null {
  try {
    const d = JSON.parse(r.details || '{}') as Record<string, unknown>
    const s = (v: unknown, max = 500) => (typeof v === 'string' && v ? v.slice(0, max) : null)
    const n = (v: unknown) => (typeof v === 'number' && Number.isFinite(v) ? v : null)
    const url = s(d.url, 1000)
    if (!url || !isCloudinaryUrl(url)) return null
    return { id: r.id, postId: r.entityId, createdAt: r.createdAt, url, publicId: s(d.publicId), width: n(d.width), height: n(d.height), bytes: n(d.bytes), prompt: s(d.prompt, 1500), style: s(d.style, 300), orientation: s(d.orientation, 20), service: s(d.service, 120), credit: s(d.credit, 200) }
  } catch {
    return null
  }
}
